export function Icon({
  name,
  className,
  strokeWidth = 1.75,
}: {
  name: string | null | undefined;
  className?: string;
  strokeWidth?: number;
}) {
  const Component = ICONS[name ?? "Stethoscope"] ?? Stethoscope;
  return <Component className={className} strokeWidth={strokeWidth} aria-hidden />;
}

export { ICONS };
