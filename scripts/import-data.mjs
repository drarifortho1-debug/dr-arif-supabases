const snake = (key) => key.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();

function convertValue(key, value) {
  if (Array.isArray(value)) return value.map((entry) => convertLegacy(entry));
  if (value === null || typeof value === "number" || typeof value === "boolean") return value;
  if (typeof value === "object") return convertLegacy(value);
  if (PLAIN_KEYS.has(key)) return value;
  return bn(value);
}

/** Convert one legacy `data` object (or repeater row) to the new shape. */
export function convertLegacy(data) {
  const out = {};
  for (const [key, value] of Object.entries(data ?? {})) {
    const nextKey = snake(key);
    out[nextKey] = convertValue(nextKey, value);
  }
  return out;
}

